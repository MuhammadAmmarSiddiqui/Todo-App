def test_expired_token_handling():
    """
    Test handling of expired JWT tokens.
    """
    print("Testing expired token handling...")

    from backend.app.core.jwt_utils import is_token_expired

    # Create an expired token
    expired_token = jwt.encode({
        "sub": "123",
        "exp": datetime.utcnow() - timedelta(minutes=1)  # Expired 1 minute ago
    }, SECRET_KEY, algorithm=ALGORITHM)

    assert is_token_expired(expired_token) is True, "Expired token should be detected as expired"

    # Verify that expired tokens cannot be validated
    assert verify_jwt_token(expired_token) is None, "Expired tokens should not validate"

    # Test authentication with expired token
    try:
        authenticate_and_authorize(expired_token, "123")
        assert False, "Should have raised HTTPException for expired token"
    except Exception as e:
        # Should raise HTTPException with 401 status
        pass

    # Create a valid token
    valid_token = jwt.encode({
        "sub": "123",
        "exp": datetime.utcnow() + timedelta(hours=1)  # Expires in 1 hour
    }, SECRET_KEY, algorithm=ALGORITHM)

    assert is_token_expired(valid_token) is False, "Valid token should not be expired"

    print("✓ Expired token handling test passed")


def test_malformed_token_rejection():
    """
    Test rejection of malformed JWT tokens.
    """
    print("Testing malformed token rejection...")

    # Various malformed tokens
    malformed_tokens = [
        "not.at.all.a.jwt",  # Not a JWT at all
        "just.a.string",     # Just a string
        "",                  # Empty string
        "abc.def",           # Too few parts
        "abc.def.ghi.jkl",   # Too many parts
        "123.456.789",       # Invalid encoding
    ]

    for token in malformed_tokens:
        result = verify_jwt_token(token)
        assert result is None, f"Malformed token '{token}' should not validate"

    print("✓ Malformed token rejection test passed")


def test_cross_service_authentication():
    """
    Test end-to-end cross-service authentication flow.
    """
    print("Testing cross-service authentication...")

    # Simulate the complete flow:
    # 1. User authenticates with Better Auth (simulated)
    # 2. Better Auth issues JWT token
    # 3. Frontend stores and sends token to backend
    # 4. Backend validates token and enforces user isolation

    # Step 1: Simulate Better Auth issuing a token
    user_id = "cross_service_user_456"
    better_auth_token = jwt.encode({
        "sub": user_id,
        "email": "crossservice@example.com",
        "name": "Cross Service User",
        "iat": datetime.utcnow(),
        "exp": datetime.utcnow() + timedelta(days=7),
        "jti": "cross-service-token-id"
    }, SECRET_KEY, algorithm=ALGORITHM)

    # Step 2: Verify token can be decoded by backend
    payload = verify_jwt_token(better_auth_token)
    assert payload is not None
    assert payload["sub"] == user_id
    assert payload["email"] == "crossservice@example.com"

    # Step 3: Verify user isolation works
    # User should be able to access their own data
    try:
        auth_result = authenticate_and_authorize(better_auth_token, user_id)
        assert auth_result is True
    except Exception as e:
        print(f"  Authentication failed: {e}")

    # User should NOT be able to access different user's data
    try:
        authenticate_and_authorize(better_auth_token, "different_user_id")
        assert False, "Should not authenticate for different user"
    except Exception:
        # Expected to fail
        pass

    print("✓ Cross-service authentication test passed")


