def test_jwt_token_generation_and_validation():
    """
    Test that JWT tokens generated by Better Auth can be validated by FastAPI backend.
    """
    print("Testing JWT token generation and validation...")

    # Simulate a token that would be generated by Better Auth
    user_id = "test_user_123"
    better_auth_token = jwt.encode({
        "sub": user_id,
        "email": "test@example.com",
        "iat": datetime.utcnow(),
        "exp": datetime.utcnow() + timedelta(days=7),
        "jti": "unique-token-id"
    }, SECRET_KEY, algorithm=ALGORITHM)

    # Backend should be able to validate this token
    payload = verify_jwt_token(better_auth_token)
    assert payload is not None, "Backend should validate Better Auth tokens"
    assert payload["sub"] == user_id, "User ID should match"
    assert payload["email"] == "test@example.com", "Email should match"

    # Extract user ID from token
    extracted_user_id = extract_user_id_from_token(better_auth_token)
    assert extracted_user_id == user_id, "User ID extraction should work"

    print("✓ JWT token generation and validation test passed")


def test_user_isolation():
    """
    Test that user isolation is properly enforced.
    """
    print("Testing user isolation...")

    # Create tokens for different users
    user_a_token = jwt.encode({
        "sub": "user_a",
        "exp": datetime.utcnow() + timedelta(hours=1)
    }, SECRET_KEY, algorithm=ALGORITHM)

    user_b_token = jwt.encode({
        "sub": "user_b",
        "exp": datetime.utcnow() + timedelta(hours=1)
    }, SECRET_KEY, algorithm=ALGORITHM)

    # Both tokens should be valid individually
    assert verify_jwt_token(user_a_token) is not None
    assert verify_jwt_token(user_b_token) is not None

    # Extract user IDs
    user_a_id = extract_user_id_from_token(user_a_token)
    user_b_id = extract_user_id_from_token(user_b_token)

    assert user_a_id == "user_a"
    assert user_b_id == "user_b"

    # User isolation check
    assert validate_user_access("user_a", "user_a") is True
    assert validate_user_access("user_a", "user_b") is False
    assert validate_user_access("user_b", "user_a") is False
    assert validate_user_access("user_b", "user_b") is True

    print("✓ User isolation test passed")


def test_authenticate_and_authorize():
    """
    Test the complete authenticate_and_authorize function.
    """
    print("Testing authenticate_and_authorize function...")

    # Create a valid token
    user_id = "auth_test_user"
    token = jwt.encode({
        "sub": user_id,
        "exp": datetime.utcnow() + timedelta(hours=1)
    }, SECRET_KEY, algorithm=ALGORITHM)

    # Should authenticate successfully when user IDs match
    result = authenticate_and_authorize(token, user_id)
    assert result is True, "Authentication should succeed when user IDs match"

    # Should raise HTTPException when user IDs don't match
    from fastapi import HTTPException
    try:
        authenticate_and_authorize(token, "different_user")
        assert False, "Should have raised HTTPException"
    except HTTPException as e:
        assert e.status_code == 403, "Should return 403 for user ID mismatch"

    # Should raise HTTPException for invalid token
    try:
        authenticate_and_authorize("invalid.token.here", user_id)
        assert False, "Should have raised HTTPException"
    except HTTPException as e:
        assert e.status_code == 401, "Should return 401 for invalid token"

    print("✓ authenticate_and_authorize test passed")


